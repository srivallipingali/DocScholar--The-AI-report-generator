"""Generate a structured report outline with Google's Gemini API.

This module is intentionally separate from the Streamlit UI and DOCX builder.
"""

import json

from google import genai
from google.genai import types


def generate_report_outline(source_text, report_title, template_name, api_key):
    """Return a report outline as a Python dictionary.

    Raises ValueError when the input is empty or Gemini returns invalid JSON.
    API/network errors from the Gemini SDK are allowed to surface to the caller.
    """
    if not source_text or not source_text.strip():
        raise ValueError("Please provide some source content.")

    if not api_key or not api_key.strip():
        raise ValueError("Gemini API key is missing.")

    client = genai.Client(api_key=api_key)

    prompt = f"""
You are helping create a well-organized report from source material.
Use only facts supported by the source. Do not invent statistics, findings,
citations, or references. If information is missing, mark it as "Not provided".

Report title: {report_title}
Report style: {template_name}

Return JSON only, using this structure:
{{
  "title": "report title",
  "sections": [
    {{
      "heading": "Introduction",
      "content": "A concise draft based on the source material",
      "subsections": [
        {{
          "heading": "Optional subsection",
          "content": "Relevant content based on the source"
        }}
      ]
    }}
  ],
  "references": []
}}

Create appropriate sections for the chosen report style. For an academic or
engineering report, consider Introduction, Objectives, Main Content, Conclusion,
and References when relevant. Do not add an index/table of contents yet; that
will be generated by the document builder later.

SOURCE MATERIAL:
{source_text}
"""

    response = client.models.generate_content(
        model="gemini-2.5-flash",
        contents=prompt,
        config=types.GenerateContentConfig(
            response_mime_type="application/json",
            temperature=0.2,
        ),
    )

    try:
        result = json.loads(response.text)
    except (json.JSONDecodeError, TypeError) as error:
        raise ValueError("Gemini did not return valid JSON. Please try again.") from error

    if not isinstance(result, dict) or not isinstance(result.get("sections"), list):
        raise ValueError("Gemini returned an unexpected report outline format.")

    return result
